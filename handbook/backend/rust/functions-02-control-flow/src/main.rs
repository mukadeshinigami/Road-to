// 10. Практические примеры
// ============================================================

fn practical_examples() {
    // Проверка чётности
    println!("is_even(4) = {}", is_even(4));
    println!("is_even(5) = {}", is_even(5));

    // Факториал
    println!("factorial(5) = {}", factorial(5));

    // Классификация возраста
    println!("classify_age(15) = {}", classify_age(15));
    println!("classify_age(25) = {}", classify_age(25));
    println!("classify_age(70) = {}", classify_age(70));
}

/// Проверка чётности числа
fn is_even(n: i32) -> bool {
    n % 2 == 0
}

/// Вычисление факториала (рекурсивно)
fn factorial(n: u32) -> u32 {
    if n == 0 || n == 1 {
        1
    } else {
        n * factorial(n - 1) // Рекурсия
    }
}

/// Классификация возраста
fn classify_age(age: u32) -> &'static str {
    if age < 13 {
        "Ребёнок"
    } else if age < 20 {
        "Подросток"
    } else if age < 65 {
        "Взрослый"
    } else {
        "Пожилой"
    }
}

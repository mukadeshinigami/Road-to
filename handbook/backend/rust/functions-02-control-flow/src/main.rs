/// Простая функция без параметров
fn greet() {
    println!("Hello, Rust!");
}

/// Функция с параметром
fn greet_with_name(name: &str) {
    println!("Hello, {}!", name);
}

// ============================================================
// 2. Параметры и возвращаемые значения
// ============================================================

/// Функция с несколькими параметрами
fn add(x: i32, y: i32) {
    let sum = x + y;
    println!("{} + {} = {}", x, y, sum);
}

/// Функция с возвращаемым значением (неявный возврат)
fn multiply(x: i32, y: i32) -> i32 {
    x * y // Нет точки с запятой — это выражение
}

// ============================================================
// 3. Выражения vs утверждения
// ============================================================

fn expressions_example() {
    // Блок как выражение
    let x = {
        let y = 3;
        y + 1 // Это выражение — возвращает значение
    };
    println!("x = {} (блок как выражение)", x);

    // Функция с выражением
    let result = calculate(5);
    println!("calculate(5) = {}", result);
}

/// Функция, демонстрирующая выражения
fn calculate(x: i32) -> i32 {
    if x > 0 {
        x * 2 // Выражение
    } else {
        x + 10 // Выражение
    }
}

// ============================================================
// 4. Условия: if, else if, else
// ============================================================

fn if_examples() {
    let number = 7;

    // Базовый if
    if number < 5 {
        println!("Число {} меньше 5", number);
    }

    // if с else
    if number < 5 {
        println!("Число {} меньше 5", number);
    } else {
        println!("Число {} больше или равно 5", number);
    }

    // if с else if
    let number2 = 7;
    if number2 < 5 {
        println!("Число {} меньше 5", number2);
    } else if number2 < 10 {
        println!("Число {} между 5 и 10", number2);
    } else {
        println!("Число {} больше или равно 10", number2);
    }

    // Условие должно быть bool
    let number3 = 3;
    if number3 != 0 {
        println!("Число {} не равно нулю", number3);
    }
}

// ============================================================
// 5. if как выражение
// ============================================================

fn if_as_expression() {
    let condition = true;
    let number = if condition {
        5 // Выражение
    } else {
        6 // Выражение
    };
    println!("number = {} (if как выражение)", number);

    // Функция max с if как выражением
    println!("max(5, 3) = {}", max(5, 3));
    println!("max(2, 8) = {}", max(2, 8));
}

/// Функция для нахождения максимума (if как выражение)
fn max(a: i32, b: i32) -> i32 {
    if a > b {
        a
    } else {
        b
    }
}

// ============================================================
// 6. Циклы: loop, while, for
// ============================================================

fn loops_examples() {
    println!("--- loop ---");
    let mut counter = 0;
    loop {
        print!("{} ", counter);
        counter += 1;
        if counter >= 5 {
            break;
        }
    }
    println!();

    // loop с возвращаемым значением
    let mut counter2 = 0;
    let result = loop {
        counter2 += 1;
        if counter2 == 10 {
            break counter2 * 2; // Возвращаем значение из loop
        }
    };
    println!("loop вернул: {}", result);

    println!("\n--- while ---");
    let mut number = 3;
    while number != 0 {
        print!("{}! ", number);
        number -= 1;
    }
    println!("LIFTOFF!!!");

    println!("\n--- for ---");
    // Итерация по диапазону
    print!("for 1..=5: ");
    for number in 1..=5 {
        print!("{} ", number);
    }
    println!();

    // Итерация по массиву
    print!("for array: ");
    let arr = [10, 20, 30, 40, 50];
    for element in arr {
        print!("{} ", element);
    }
    println!();
}

// ============================================================
// 7. break и continue
// ============================================================

fn break_continue_examples() {
    println!("--- break ---");
    let mut counter = 0;
    loop {
        counter += 1;
        if counter == 5 {
            break; // Выходим из цикла
        }
        print!("{} ", counter);
    }
    println!("\nПосле break");

    println!("\n--- continue ---");
    print!("Нечётные числа от 1 до 10: ");
    for number in 1..=10 {
        if number % 2 == 0 {
            continue; // Пропускаем чётные числа
        }
        print!("{} ", number);
    }
    println!();

    // Поиск первого чётного числа
    println!("\n--- Поиск первого чётного ---");
    let numbers = [1, 3, 5, 8, 9, 11];
    for num in numbers {
        if num % 2 == 0 {
            println!("Найдено первое чётное число: {}", num);
            break;
        }
    }
}


// 8. match выражение
// ============================================================

fn match_examples() {
    let number = 3;

    // Базовый match
    match number {
        1 => println!("Один"),
        2 => println!("Два"),
        3 => println!("Три"),
        _ => println!("Другое число"),
    }

    // match как выражение
    let number2 = 3;
    let word = match number2 {
        1 => "один",
        2 => "два",
        3 => "три",
        _ => "другое",
    };
    println!("match вернул: {}", word);

    // Несколько значений в одной ветке
    let number3 = 2;
    match number3 {
        1 | 2 => println!("Один или два"),
        3 | 4 => println!("Три или четыре"),
        _ => println!("Другое"),
    }

    // Диапазоны в match
    let number4 = 42;
    match number4 {
        1..=10 => println!("От 1 до 10"),
        11..=50 => println!("От 11 до 50"),
        _ => println!("Больше 50 или меньше 1"),
    }

    // Классификация числа
    let number5 = -5;
    match number5 {
        n if n > 0 => println!("{} - положительное", n),
        n if n < 0 => println!("{} - отрицательное", n),
        _ => println!("Ноль"),
    }
}

// ============================================================
// 9. return - явный и неявный
// ============================================================

fn return_examples() {
    // Неявный возврат (рекомендуемый стиль)
    println!("add_implicit(5, 3) = {}", add_implicit(5, 3));

    // Явный return
    println!("add_explicit(5, 3) = {}", add_explicit(5, 3));

    // Ранний выход с return
    match divide(10, 5) {
        Some(result) => println!("10 / 5 = {}", result),
        None => println!("Деление на ноль!"),
    }

    match divide(10, 0) {
        Some(result) => println!("10 / 0 = {}", result),
        None => println!("Деление на ноль!"),
    }

    // Множественные return
    println!("check_number(-5) = {}", check_number(-5));
    println!("check_number(0) = {}", check_number(0));
    println!("check_number(5) = {}", check_number(5));
}

/// Неявный возврат (рекомендуемый стиль)
fn add_implicit(x: i32, y: i32) -> i32 {
    x + y // Нет точки с запятой
}

/// Явный return
fn add_explicit(x: i32, y: i32) -> i32 {
    return x + y;
}

/// Функция с ранним выходом
fn divide(a: i32, b: i32) -> Option<i32> {
    if b == 0 {
        return None; // Ранний выход
    }
    Some(a / b) // Обычный возврат
}

/// Функция с множественными return
fn check_number(x: i32) -> &'static str {
    if x < 0 {
        return "Отрицательное";
    }
    if x == 0 {
        return "Ноль";
    }
    "Положительное" // Последний возврат без return
}

